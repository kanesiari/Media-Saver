/**
 * Creates a valid, minimal ISO MP4 container with 'ftyp' and 'moov' boxes.
 */
export function createValidMp4Buffer(): Uint8Array {
  // Minimal valid MP4 container header: ftypisom
  const ftypBox = [
    0x00, 0x00, 0x00, 0x18, // box size: 24 bytes
    0x66, 0x74, 0x79, 0x70, // 'ftyp'
    0x69, 0x73, 0x6f, 0x6d, // major brand: 'isom'
    0x00, 0x00, 0x02, 0x00, // minor version
    0x69, 0x73, 0x6f, 0x6d, // compatible brand: 'isom'
    0x6d, 0x70, 0x34, 0x31, // compatible brand: 'mp41'
  ];

  const moovBox = [
    0x00, 0x00, 0x00, 0x08, // box size: 8 bytes
    0x6d, 0x6f, 0x6f, 0x76, // 'moov'
  ];

  return new Uint8Array([...ftypBox, ...moovBox]);
}

/**
 * Helper to convert an async ReadableStream<Uint8Array> into a single combined Uint8Array.
 */
export async function streamToUint8Array(stream: ReadableStream<Uint8Array> | null): Promise<Uint8Array> {
  if (!stream) return new Uint8Array(0);
  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let totalLength = 0;

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    if (value) {
      chunks.push(value);
      totalLength += value.length;
    }
  }

  const result = new Uint8Array(totalLength);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.length;
  }
  return result;
}
